        /// <summary>
        /// Returns the translated string for the given key using the current language.
        /// Falls back to English if the key is not found in the current language.
        /// Returns the key itself surrounded by brackets if not found at all.
        /// </summary>
        public static string T(string key)
        {
            if (Translations.TryGetValue(_currentLanguage, out var lang) && lang.TryGetValue(key, out var value))
                return value;

            if (_currentLanguage != "en" && Translations.TryGetValue("en", out var en) && en.TryGetValue(key, out var fallback))
                return fallback;

            return $"[{key}]";
        }

        /// <summary>
        /// Sets the active language. If the language code is not supported, defaults to English.
        /// </summary>
        public static void SetLanguage(string langCode)
        {
            _currentLanguage = Translations.ContainsKey(langCode) ? langCode : "en";
        }

        /// <summary>
        /// Gets the current language code.
        /// </summary>
        public static string GetCurrentLanguage() => _currentLanguage;

        /// <summary>
        /// Returns a dictionary of available language codes mapped to their native names.
        /// </summary>
        public static Dictionary<string, string> GetAvailableLanguages() => new(LanguageNames);
